"""Analysis report generation (Markdown). Calculated statistics are kept
visually separate from AI-generated narrative, with timestamps and caveats."""
from __future__ import annotations

from datetime import datetime, timezone

import pandas as pd

from config.settings import settings
from src.ai.schemas import InsightResponse
from src.analytics.kpis import compute_kpis
from src.data.profiling import profile_dataset


def _fmt_value(v, fmt: str) -> str:
    if v is None:
        return "n/a"
    if fmt == "currency":
        return f"${v:,.2f}"
    if fmt == "percent":
        return f"{v:.2f}%"
    if fmt == "count":
        return f"{int(v):,}"
    return f"{v:,.2f}"


def build_markdown_report(df: pd.DataFrame, dataset_name: str,
                          filters_desc: dict | None = None,
                          insight: InsightResponse | None = None,
                          ai_used: bool = False) -> str:
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    p = profile_dataset(df)
    lines: list[str] = [
        "# AI Insights Dashboard — Analysis Report",
        "",
        f"- **Dataset:** {dataset_name} ({'synthetic demo data' if 'sample' in dataset_name.lower() else 'user upload'})",
        f"- **Generated:** {now}",
        f"- **Rows:** {p.n_rows:,}  |  **Columns:** {p.n_cols}",
        f"- **Applied filters:** {filters_desc or 'none'}",
        "",
        "## 1. Computed KPIs (deterministic — calculated by pandas)",
        "",
        "| KPI | Value | Formula |",
        "|---|---:|---|",
    ]
    for k in compute_kpis(df):
        lines.append(f"| {k.label} | {_fmt_value(k.value, k.fmt)} | `{k.formula}` |")

    lines += [
        "",
        "## 2. Data Quality Profile",
        "",
        f"- Missing cells: {p.total_missing_cells:,} ({(p.total_missing_cells / max(p.n_rows * p.n_cols, 1)):.2%} of all cells)",
        f"- Duplicate rows: {p.duplicate_rows}",
        f"- Date coverage: {p.date_ranges or 'no date column detected'}",
    ]
    for w in p.warnings:
        lines.append(f"- Warning: {w}")

    if insight is not None:
        lines += ["", "## 3. AI-Generated Narrative", ""]
        if ai_used:
            lines.append(
                "> The text in this section was generated by "
                f"'{settings.openai_model}' interpreting the computed statistics above. "
                "It is commentary, not measurement."
            )
        else:
            lines.append("> AI narrative unavailable — the summary below is raw computed statistics.")
        lines += ["", f"**Summary.** {insight.summary}", ""]
        if insight.findings:
            lines.append("**Findings**")
            lines += [f"- {f}" for f in insight.findings] + [""]
        if insight.supporting_metrics:
            lines.append("**Supporting metrics (as cited by the model)**")
            lines += [f"- {m.name}: {m.value}" for m in insight.supporting_metrics] + [""]
        if insight.caveats:
            lines.append("**Caveats & limitations**")
            lines += [f"- {c}" for c in insight.caveats] + [""]
        if insight.recommended_investigations:
            lines.append("**Recommended investigations**")
            lines += [f"- {r}" for r in insight.recommended_investigations] + [""]

    lines += [
        "",
        "## 4. Methodological Notes",
        "",
        "- All numeric values in sections 1–2 were computed locally with pandas; no AI was involved.",
        "- Statistical outliers are flagged by the IQR rule and are not, by themselves, evidence of error or fraud.",
        "- Correlation does not establish causation.",
        "- The demo dataset is synthetic, generated with a fixed random seed. It is not real company or market data.",
        "- Uploaded data is processed in memory per session and is not sent to any external service except as a "
        "bounded statistical summary when you explicitly ask an AI question.",
        "",
    ]
    return "\n".join(lines)
